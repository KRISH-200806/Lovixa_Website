async function seedBlogPosts() {
  console.log('🚀 Seeding BlogPosts collection into Payload CMS...')
  const payload = await getPayload({ config })

  for (const postData of SEED_BLOGS) {
    try {
      const existing = await payload.find({
        collection: 'blog-posts',
        where: {
          slug: { equals: postData.slug },
        },
        limit: 1,
      })

      if (existing.docs.length > 0) {
        const id = existing.docs[0].id
        console.log(`Updating existing article: "${postData.title}"...`)
        await payload.update({
          collection: 'blog-posts',
          id,
          data: postData as any,
        })
        console.log(`  ✓ Updated post: ${postData.slug}`)
      } else {
        console.log(`Creating new article: "${postData.title}"...`)
        await payload.create({
          collection: 'blog-posts',
          data: postData as any,
        })
        console.log(`  ✓ Created post: ${postData.slug}`)
      }
    } catch (err: any) {
      console.error(`  ❌ Failed to seed post "${postData.slug}":`, err.message || err)
    }
  }

  console.log('🎉 BlogPosts successfully seeded in Payload CMS!')
  process.exit(0)
}

seedBlogPosts().catch((err) => {
  console.error('Fatal blog seeding error:', err)
  process.exit(1)
})
